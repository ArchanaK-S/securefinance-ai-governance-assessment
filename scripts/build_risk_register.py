#!/usr/bin/env python3
"""Validate risk_register.csv, add scores/ratings, and emit a Markdown table + heat-map figure."""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "risk-register" / "risk_register.csv"


def rating(score: int) -> str:
    return "Critical" if score >= 20 else "High" if score >= 12 else "Medium" if score >= 6 else "Low"


def main() -> None:
    df = pd.read_csv(SRC)
    for c in ("likelihood_1_5", "impact_1_5", "residual_likelihood_1_5", "residual_impact_1_5"):
        assert df[c].between(1, 5).all(), f"{c} must be within 1-5"
    assert df["risk_id"].is_unique and len(df) >= 8, "register needs >= 8 unique risks"
    df["inherent_score"] = df["likelihood_1_5"] * df["impact_1_5"]
    df["inherent_rating"] = df["inherent_score"].map(rating)
    df["residual_score"] = df["residual_likelihood_1_5"] * df["residual_impact_1_5"]
    df["residual_rating"] = df["residual_score"].map(rating)
    assert (df["residual_score"] <= df["inherent_score"]).all(), "controls must not increase risk"
    df.to_csv(ROOT / "risk-register" / "risk_register_scored.csv", index=False)

    cols = ["risk_id", "category", "risk_description", "likelihood_1_5", "impact_1_5", "inherent_rating",
            "accountable_owner", "existing_or_proposed_control", "residual_rating", "residual_score"]
    lines = ["# AI Risk Register - SecureFinance Africa\n",
             "> Generated by `scripts/build_risk_register.py` from `risk_register.csv`. Do not edit by hand.\n",
             "Scoring: score = likelihood x impact (1-5 each). Rating: 1-5 Low, 6-11 Medium, 12-19 High, 20-25 Critical.\n"]
    lines.append("| " + " | ".join(cols) + " |")
    lines.append("|" + "---|" * len(cols))
    for _, r in df.iterrows():
        lines.append("| " + " | ".join(str(r[c]).replace("|", "/") for c in cols) + " |")
    (ROOT / "risk-register" / "risk_register.md").write_text("\n".join(lines) + "\n")

    fig, axes = plt.subplots(1, 2, figsize=(10, 4.4), sharey=True)
    for ax, (lk, im, title) in zip(axes, (("likelihood_1_5", "impact_1_5", "Inherent risk"),
                                          ("residual_likelihood_1_5", "residual_impact_1_5", "Residual risk (after controls)"))):
        grid = np.add.outer(np.arange(1, 6), np.zeros(5)) * np.arange(1, 6)[None, :]
        ax.imshow(grid, origin="lower", cmap="RdYlGn_r", extent=(0.5, 5.5, 0.5, 5.5), alpha=0.55, vmin=1, vmax=25)
        for key, sub in df.groupby([lk, im]):
            ax.text(key[1], key[0], "\n".join(sub["risk_id"]) if len(sub) <= 3 else
                    ", ".join(sub["risk_id"]), ha="center", va="center", fontsize=6.5, fontweight="bold")
        ax.set_xlabel("Impact"); ax.set_title(title, fontsize=10, fontweight="bold")
        ax.set_xticks(range(1, 6)); ax.set_yticks(range(1, 6))
    axes[0].set_ylabel("Likelihood")
    fig.tight_layout()
    out = ROOT / "results" / "figures" / "fig5_risk_heatmap.png"
    out.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out, dpi=150, bbox_inches="tight")
    print(f"Risk register OK: {len(df)} risks | inherent High+ = {(df.inherent_score >= 12).sum()} | residual High+ = {(df.residual_score >= 12).sum()}")


if __name__ == "__main__":
    main()
